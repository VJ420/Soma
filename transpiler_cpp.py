"""
Fractal to C++ Transpiler.
Translates Fractal code into high-performance, modern C++20.
Enables 'Halwa' syntax to run with raw native machine speed!
"""
from typing import List, Optional
from ast_nodes import (
    ASTNode, ProgramNode, CellDefNode, AssignmentNode, MemberAssignmentNode,
    PipelineNode, CallNode, MemberAccessNode, BinaryOpNode, UnaryOpNode,
    LiteralNode, IdentifierNode, ListNode, IfNode, ForNode, WhileNode
)

class CppTranspiler:
    def __init__(self):
        self.indent_level = 0
        self.header_includes = {
            "<iostream>",
            "<vector>",
            "<string>",
            "<cmath>",
            "<functional>",
            "<any>"
        }
        self.struct_definitions: List[str] = []

    def _indent(self) -> str:
        return "  " * self.indent_level

    def transpile(self, program: ProgramNode) -> str:
        body_lines: List[str] = []
        
        self.indent_level = 1
        for stmt in program.statements:
            line = self._transpile_stmt(stmt)
            if line:
                body_lines.append(line)

        # Build final C++ code
        includes = "\n".join(f"#include {inc}" for inc in sorted(self.header_includes))
        structs = "\n\n".join(self.struct_definitions)
        main_body = "\n".join(body_lines)

        cpp_code = f"""// Generated by Fractal C++ Engine
// Target: Modern C++20 Native Performance
{includes}

// Standard helper print functions
template <typename... Args>
void print(Args&&... args) {{
    ((std::cout << args << " "), ...);
    std::cout << "\\n";
}}

{structs}

int main() {{
{main_body}
    return 0;
}}
"""
        return cpp_code

    def _transpile_stmt(self, node: ASTNode) -> str:
        if isinstance(node, CellDefNode):
            if node.params is not None:
                # Transpile as a function
                param_strs = [f"auto {p}" for p in node.params]
                body_code = self._transpile_block(node.body)
                fn_code = f"{self._indent()}auto {node.name} = [{self._indent()}copy = true]({', '.join(param_strs)}) {{\n{body_code}\n{self._indent()}}};"
                return fn_code
            else:
                # 0-parameter cell (variable or nested struct)
                if len(node.body) == 1 and not isinstance(node.body[0], CellDefNode):
                    val_code = self._transpile_expr(node.body[0])
                    return f"{self._indent()}auto {node.name} = {val_code};"
                else:
                    # Module / Struct
                    struct_lines = []
                    struct_lines.append(f"struct Module_{node.name} {{")
                    for child in node.body:
                        if isinstance(child, CellDefNode):
                            if child.params is not None:
                                p_strs = [f"auto {p}" for p in child.params]
                                b_code = self._transpile_block(child.body, extra_indent=1)
                                struct_lines.append(f"  auto {child.name}({', '.join(p_strs)}) {{\n{b_code}\n  }}")
                            else:
                                v = self._transpile_expr(child.body[0]) if child.body else "0"
                                struct_lines.append(f"  decltype({v}) {child.name} = {v};")
                    struct_lines.append("};")
                    self.struct_definitions.append("\n".join(struct_lines))
                    return f"{self._indent()}Module_{node.name} {node.name};"

        if isinstance(node, AssignmentNode):
            return f"{self._indent()}{node.target} = {self._transpile_expr(node.value)};"

        if isinstance(node, MemberAssignmentNode):
            tgt = self._transpile_expr(node.target)
            return f"{self._indent()}{tgt}.{node.member} = {self._transpile_expr(node.value)};"

        if isinstance(node, IfNode):
            cond = self._transpile_expr(node.condition)
            then_code = self._transpile_block(node.then_body)
            code = f"{self._indent()}if ({cond}) {{\n{then_code}\n{self._indent()}}}"
            if node.else_body:
                else_code = self._transpile_block(node.else_body)
                code += f" else {{\n{else_code}\n{self._indent()}}}"
            return code

        if isinstance(node, ForNode):
            iter_code = self._transpile_expr(node.iterable)
            body_code = self._transpile_block(node.body)
            return f"{self._indent()}for (auto&& {node.var_name} : {iter_code}) {{\n{body_code}\n{self._indent()}}}"

        if isinstance(node, WhileNode):
            cond = self._transpile_expr(node.condition)
            body_code = self._transpile_block(node.body)
            return f"{self._indent()}while ({cond}) {{\n{body_code}\n{self._indent()}}}"

        expr_code = self._transpile_expr(node)
        return f"{self._indent()}{expr_code};"

    def _transpile_block(self, stmts: List[ASTNode], extra_indent: int = 0) -> str:
        self.indent_level += 1 + extra_indent
        lines = []
        for i, stmt in enumerate(stmts):
            is_last = (i == len(stmts) - 1)
            # If last statement in a function body is an expression, return it
            if is_last and not isinstance(stmt, (CellDefNode, AssignmentNode, MemberAssignmentNode, IfNode, ForNode, WhileNode)):
                lines.append(f"{self._indent()}return {self._transpile_expr(stmt)};")
            else:
                lines.append(self._transpile_stmt(stmt))
        self.indent_level -= 1 + extra_indent
        return "\n".join(lines)

    def _transpile_expr(self, node: ASTNode) -> str:
        if isinstance(node, LiteralNode):
            if isinstance(node.value, str):
                escaped = node.value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t')
                return f'std::string("{escaped}")'
            if isinstance(node.value, bool):
                return "true" if node.value else "false"
            if node.value is None:
                return "nullptr"
            return str(node.value)

        if isinstance(node, IdentifierNode):
            return node.name

        if isinstance(node, ListNode):
            elements = [self._transpile_expr(e) for e in node.elements]
            return f"std::vector{{{', '.join(elements)}}}"

        if isinstance(node, MemberAccessNode):
            target = self._transpile_expr(node.target)
            return f"{target}.{node.member}"

        if isinstance(node, CallNode):
            callee = self._transpile_expr(node.callee)
            args = [self._transpile_expr(a) for a in node.args]
            return f"{callee}({', '.join(args)})"

        if isinstance(node, PipelineNode):
            left = self._transpile_expr(node.left)
            if isinstance(node.right, CallNode):
                callee = self._transpile_expr(node.right.callee)
                other_args = [self._transpile_expr(a) for a in node.right.args]
                args = [left] + other_args
                return f"{callee}({', '.join(args)})"
            else:
                right = self._transpile_expr(node.right)
                return f"{right}({left})"

        if isinstance(node, BinaryOpNode):
            left = self._transpile_expr(node.left)
            right = self._transpile_expr(node.right)
            if node.op == "^":
                return f"std::pow({left}, {right})"
            return f"({left} {node.op} {right})"

        if isinstance(node, UnaryOpNode):
            inner = self._transpile_expr(node.expr)
            if node.op == "not":
                return f"!({inner})"
            return f"({node.op}{inner})"

        return "/* unknown node */"
