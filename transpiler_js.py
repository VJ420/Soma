"""
Soma to JavaScript transpiler.
The generated program runs on Node and V8. This is Soma's fast execution path.
"""
import os
from typing import List, Optional
from lexer import Lexer
from parser import Parser
from ast_nodes import (
    ASTNode, ProgramNode, CellDefNode, AssignmentNode, MemberAssignmentNode,
    PipelineNode, CallNode, MemberAccessNode, BinaryOpNode, UnaryOpNode,
    LiteralNode, IdentifierNode, ListNode, MapNode, IfNode, ForNode, WhileNode,
    IndexAccessNode, IndexAssignmentNode, MatchNode, UseNode, SpawnNode
)


class TranspileError(NotImplementedError):
    """Raised when a Soma construct cannot run on the V8 path."""


class JsTranspiler:
    def __init__(self, base_dir: str = "."):
        self.indent_level = 0
        self.base_dir = base_dir
        self.bound_names: set[str] = set()

    def _indent(self) -> str:
        return "  " * self.indent_level

    def transpile(self, program: ProgramNode) -> str:
        lines = [
            "// Generated by the Soma V8 engine",
            'const { performance } = require("perf_hooks");',
            "const print = (...args) => { console.log(...args); return args[args.length - 1]; };",
            "const len = (x) => x.length;",
            "const range = (...args) => {",
            "  const start = args.length === 1 ? 0 : args[0];",
            "  const stop = args.length === 1 ? args[0] : args[1];",
            "  const step = args.length < 3 ? 1 : args[2];",
            "  const out = [];",
            "  if (step > 0) { for (let i = start; i < stop; i += step) out.push(i); }",
            "  else { for (let i = start; i > stop; i += step) out.push(i); }",
            "  return out;",
            "};",
            "const str = (x) => String(x);",
            "const int = (x) => parseInt(x, 10);",
            "const float = (x) => parseFloat(x);",
            "const type = (x) => x === null ? 'NoneType' : typeof x;",
            "const sqrt = Math.sqrt;",
            "const sin = Math.sin;",
            "const cos = Math.cos;",
            "const abs = Math.abs;",
            "const time = () => Date.now() / 1000;",
            "const perf = () => performance.now() / 1000;",
            "const map = (items, fn) => items.map((item) => fn(item));",
            "const filter = (items, fn) => items.filter((item) => fn(item));",
            "const push = (items, item) => { items.push(item); return items; };",
            ""
        ]
        assigned = self._collect_assignments(program.statements)
        if assigned:
            lines.append(f"let {', '.join(sorted(assigned))};")
        for stmt in program.statements:
            line = self._transpile_stmt(stmt)
            if line:
                lines.append(line)
        return "\n".join(lines)

    def _collect_assignments(self, nodes: List[ASTNode]) -> set[str]:
        """Collect function-scoped bindings without crossing nested cell scopes."""
        names: set[str] = set()
        for node in nodes:
            if isinstance(node, AssignmentNode):
                names.add(node.target)
            elif isinstance(node, IfNode):
                names.update(self._collect_assignments(node.then_body))
                if node.else_body:
                    names.update(self._collect_assignments(node.else_body))
            elif isinstance(node, (ForNode, WhileNode)):
                names.update(self._collect_assignments(node.body))
        return names

    def _transpile_stmt(self, node: ASTNode) -> str:
        if isinstance(node, CellDefNode):
            child_defs = [child.name for child in node.body if isinstance(child, CellDefNode)]
            if node.params is not None:
                p_str = ", ".join(node.params)
                exports = (node.params + child_defs) if child_defs else None
                body = self._transpile_block(node.body, auto_export=exports, predeclared=node.params)
                return f"{self._indent()}const {node.name} = ({p_str}) => {{\n{body}\n{self._indent()}}};"
            else:
                if len(node.body) == 1 and not isinstance(node.body[0], CellDefNode):
                    v = self._transpile_expr(node.body[0])
                    return f"{self._indent()}const {node.name} = {v};"
                else:
                    body = self._transpile_block(node.body, auto_export=child_defs)
                    return f"{self._indent()}const {node.name} = (() => {{\n{body}\n{self._indent()}}})();"

        if isinstance(node, AssignmentNode):
            return f"{self._indent()}{node.target} = {self._transpile_expr(node.value)};"

        if isinstance(node, MemberAssignmentNode):
            return f"{self._indent()}{self._transpile_expr(node.target)}.{node.member} = {self._transpile_expr(node.value)};"

        if isinstance(node, IndexAssignmentNode):
            return f"{self._indent()}{self._transpile_expr(node.target)}[{self._transpile_expr(node.index)}] = {self._transpile_expr(node.value)};"

        if isinstance(node, IfNode):
            cond = self._transpile_expr(node.condition)
            then_b = self._transpile_block(node.then_body, declare_assignments=False)
            code = f"{self._indent()}if ({cond}) {{\n{then_b}\n{self._indent()}}}"
            if node.else_body:
                else_b = self._transpile_block(node.else_body, declare_assignments=False)
                code += f" else {{\n{else_b}\n{self._indent()}}}"
            return code

        if isinstance(node, WhileNode):
            cond = self._transpile_expr(node.condition)
            b = self._transpile_block(node.body, declare_assignments=False)
            return f"{self._indent()}while ({cond}) {{\n{b}\n{self._indent()}}}"

        if isinstance(node, ForNode):
            iter_e = self._transpile_expr(node.iterable)
            b = self._transpile_block(node.body, declare_assignments=False)
            return f"{self._indent()}for (const {node.var_name} of {iter_e}) {{\n{b}\n{self._indent()}}}"

        if isinstance(node, UseNode):
            return self._transpile_use(node)

        if isinstance(node, SpawnNode):
            raise TranspileError(
                "spawn runs on the Soma interpreter. Use --engine interpreter."
            )

        return f"{self._indent()}{self._transpile_expr(node)};"

    def _transpile_block(
        self,
        stmts: List[ASTNode],
        auto_export: Optional[List[str]] = None,
        predeclared: Optional[List[str]] = None,
        declare_assignments: bool = True,
    ) -> str:
        self.indent_level += 1
        lines = []
        saved_names = set(self.bound_names)
        self.bound_names.update(predeclared or [])
        if declare_assignments:
            assigned = self._collect_assignments(stmts)
            assigned.difference_update(self.bound_names)
            self.bound_names.update(assigned)
            if assigned:
                lines.append(f"{self._indent()}let {', '.join(sorted(assigned))};")
        for i, stmt in enumerate(stmts):
            is_last = (i == len(stmts) - 1)
            if is_last and not isinstance(stmt, (CellDefNode, AssignmentNode, MemberAssignmentNode, IndexAssignmentNode, IfNode, ForNode, WhileNode)) and not auto_export:
                lines.append(f"{self._indent()}return {self._transpile_expr(stmt)};")
            else:
                lines.append(self._transpile_stmt(stmt))
        
        if auto_export:
            lines.append(f"{self._indent()}return {{ {', '.join(auto_export)} }};")

        self.indent_level -= 1
        self.bound_names = saved_names
        return "\n".join(lines)

    def _transpile_expr(self, node: ASTNode) -> str:
        if isinstance(node, LiteralNode):
            if isinstance(node.value, str):
                return repr(node.value)
            if isinstance(node.value, bool):
                return "true" if node.value else "false"
            if node.value is None:
                return "null"
            return str(node.value)

        if isinstance(node, IdentifierNode):
            return node.name

        if isinstance(node, ListNode):
            return f"[{', '.join(self._transpile_expr(e) for e in node.elements)}]"

        if isinstance(node, MapNode):
            pairs = ", ".join(
                f"[{self._transpile_expr(key)}]: {self._transpile_expr(value)}"
                for key, value in node.pairs
            )
            return f"({{{pairs}}})"

        if isinstance(node, MatchNode):
            return self._transpile_match(node)

        if isinstance(node, MemberAccessNode):
            return f"{self._transpile_expr(node.target)}.{node.member}"

        if isinstance(node, IndexAccessNode):
            return f"{self._transpile_expr(node.target)}[{self._transpile_expr(node.index)}]"

        if isinstance(node, CallNode):
            args = ", ".join(self._transpile_expr(a) for a in node.args)
            return f"{self._transpile_expr(node.callee)}({args})"

        if isinstance(node, PipelineNode):
            left = self._transpile_expr(node.left)
            if isinstance(node.right, CallNode):
                callee = self._transpile_expr(node.right.callee)
                other = [self._transpile_expr(a) for a in node.right.args]
                args = ", ".join([left] + other)
                return f"{callee}({args})"
            else:
                right = self._transpile_expr(node.right)
                return f"{right}({left})"

        if isinstance(node, BinaryOpNode):
            left = self._transpile_expr(node.left)
            right = self._transpile_expr(node.right)
            op = node.op
            if op == "^":
                return f"Math.pow({left}, {right})"
            if op == "and":
                op = "&&"
            elif op == "or":
                op = "||"
            return f"({left} {op} {right})"

        if isinstance(node, UnaryOpNode):
            inner = self._transpile_expr(node.expr)
            if node.op == "not":
                return f"!({inner})"
            return f"({node.op}{inner})"

        raise TranspileError(
            f"{type(node).__name__} cannot run on the Soma V8 engine. "
            "Use --engine interpreter."
        )

    def _transpile_match(self, node: MatchNode) -> str:
        lines = [f"(() => {{ const __subject = {self._transpile_expr(node.subject)};"]
        for case in node.cases:
            body = self._match_body(case.body)
            guard = self._transpile_expr(case.guard) if case.guard is not None else "true"
            if isinstance(case.pattern, IdentifierNode) and case.pattern.name == "_":
                lines.append(f"if ({guard}) {{ {body} }}")
            elif isinstance(case.pattern, IdentifierNode):
                lines.append(
                    f"{{ const {case.pattern.name} = __subject; if ({guard}) {{ {body} }} }}"
                )
            else:
                compared = f"__subject === {self._transpile_expr(case.pattern)}"
                condition = compared if case.guard is None else f"({compared}) && ({guard})"
                lines.append(f"if ({condition}) {{ {body} }}")
        lines.append("return null; })()")
        return " ".join(lines)

    def _match_body(self, statements: List[ASTNode]) -> str:
        if len(statements) == 1 and not isinstance(
            statements[0],
            (CellDefNode, AssignmentNode, MemberAssignmentNode, IndexAssignmentNode, IfNode, ForNode, WhileNode),
        ):
            return f"return {self._transpile_expr(statements[0])};"
        return " ".join(self._transpile_block(statements).splitlines())

    def _resolve_module(self, module_path: str) -> str:
        candidate = module_path if os.path.isabs(module_path) else os.path.join(self.base_dir, module_path)
        for suffix in ("", ".sm", ".fc"):
            resolved = candidate + suffix
            if os.path.isfile(resolved):
                return resolved
        raise TranspileError(f"Soma module not found: {module_path}")

    def _transpile_use(self, node: UseNode) -> str:
        resolved = self._resolve_module(node.module_path)
        previous = self.base_dir
        self.base_dir = os.path.dirname(resolved) or previous
        try:
            with open(resolved, "r", encoding="utf-8") as handle:
                source = handle.read()
            program = Parser(Lexer(source).tokenize()).parse()
        finally:
            self.base_dir = previous
        names = [
            stmt.name for stmt in program.statements
            if isinstance(stmt, CellDefNode) or isinstance(stmt, AssignmentNode)
        ]
        alias = node.alias or os.path.splitext(os.path.basename(resolved))[0]
        body = self._transpile_block(program.statements, auto_export=names)
        return f"{self._indent()}const {alias} = (() => {{\n{body}\n{self._indent()}}})();"
